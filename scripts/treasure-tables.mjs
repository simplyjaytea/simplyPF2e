/** The four-PC row for a party level; an out-of-range or non-integer level throws. */
export function partyTreasureRow(level) {
  if (!Number.isInteger(level) || level < TREASURE_MIN_PARTY_LEVEL || level > TREASURE_MAX_PARTY_LEVEL) {
    throw new Error(
      `Party level must be an integer from ${TREASURE_MIN_PARTY_LEVEL} to ${TREASURE_MAX_PARTY_LEVEL}, got ${String(level)}`
    );
  }
  return PARTY_TREASURE_BY_LEVEL[level - TREASURE_MIN_PARTY_LEVEL];
}

/**
 * The row adjusted for party size (GM Core: "for each additional character" add
 * one permanent item of the party's level or 1 level higher, two consumables
 * usually one of the party's level and one of 1 level higher, and the Currency
 * per Additional PC value).
 *
 * extraPcs = max(0, partySize - 4), so a party under four uses the four-PC row
 * unchanged. The extra consumables are merged by item level and sorted from the
 * highest level down; the extra permanent item is recorded, not filled. The
 * returned object and its arrays are fresh copies; the table is never mutated.
 */
export function partyTreasureForSize(level, partySize) {
  const row = partyTreasureRow(level);
  if (!Number.isInteger(partySize) || partySize < PARTY_SIZE_MIN || partySize > PARTY_SIZE_MAX) {
    throw new Error(
      `Party size must be an integer from ${PARTY_SIZE_MIN} to ${PARTY_SIZE_MAX}, got ${String(partySize)}`
    );
  }

  const extraPcs = Math.max(0, partySize - BASE_PARTY_SIZE);
  const extraLevels = [level, Math.min(level + 1, TREASURE_MAX_PARTY_LEVEL)];

  const counts = new Map(row.consumables.map((entry) => [entry.level, entry.count]));
  for (let pc = 0; pc < extraPcs; pc++) {
    for (const itemLevel of extraLevels) counts.set(itemLevel, (counts.get(itemLevel) ?? 0) + 1);
  }
  const consumables = [...counts.entries()]
    .sort((a, b) => b[0] - a[0])
    .map(([itemLevel, count]) => ({ level: itemLevel, count }));

  return {
    ...row,
    permanent: row.permanent.map((entry) => ({ level: entry.level, count: entry.count })),
    partySize,
    extraPcs,
    belowBase: partySize < BASE_PARTY_SIZE,
    consumables,
    permanentExtra: { count: extraPcs, levels: [...extraLevels] },
    currencyGp: row.currencyGp + extraPcs * row.currencyPerExtraPcGp
  };
}
